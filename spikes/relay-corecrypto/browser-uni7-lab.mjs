async function context(wallet) {
  const ctx = await browser.newContext();
  await ctx.addInitScript(address => {
    window.keplr = {
      experimentalSuggestChain: async () => {}, enable: async () => {},
      getOfflineSigner: () => ({ getAccounts: async () => [{ address }] }),
      signDirect: async () => ({}), signAmino: async () => ({})
    };
  }, wallet);
  await ctx.route('https://juno.test.api.nodeshub.online/**', async route => {
    const path = new URL(route.request().url()).pathname;
    let data;
    if (path.endsWith('/node_info')) data = { default_node_info: { network: 'uni-7' } };
    else if (path.endsWith('/contract/' + contract)) data = { contract_info: {
      creator: 'juno1z3xcalwan92yqxu9d406tlft9yy94jy8s5et57', label: 'NETA RELAY mailbox v0.1 · UNI-7', code_id: '42' } };
    else if (path.endsWith('/code/42')) data = { code_info: {
      data_hash: 'e02c7918d1f8da0f662a0720fc3668765d79ededce8e9e9dcccff9aae2b9e64a' } };
    else if (path.includes('/smart/')) {
      const query = JSON.parse(atob(decodeURIComponent(path.split('/smart/')[1])));
      if (query.device) data = { data: devices.get(query.device.address) || null };
      else if (query.inbox) data = { data: { messages:
        (inbox.get(query.inbox.address) || []).filter(item => item.sequence > (query.inbox.after || 0)) } };
      else if (query.sent) data = { data: sent.get(query.sent.sender + ':' + query.sent.message_id) || null };
    }
    await route.fulfill({ status: data ? 200 : 404, contentType: 'application/json',
      headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(data || {}) });
  });
  return ctx;
}
async function ready(page, pattern) {
  try { await page.waitForFunction(text => document.querySelector('#status')?.textContent.includes(text), pattern,
    { timeout: 12000 }); }
  catch (error) { throw Error('Waiting for ' + pattern + ' but got: ' + await page.locator('#status').textContent(), { cause: error }); }
}
