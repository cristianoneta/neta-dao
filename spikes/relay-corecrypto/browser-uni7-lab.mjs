const server = http.createServer(async (req, res) => {
  const path = new URL(req.url, 'http://localhost').pathname;
  if (path === '/mock/execute') {
    const chunks = []; for await (const part of req) chunks.push(part);
    const { sender, contract: target, msg } = JSON.parse(Buffer.concat(chunks).toString());
    if (target !== contract || ![alice,bob].includes(sender)) { res.writeHead(400).end('wrong account'); return; }
    if (msg.register) {
      if (devices.has(sender)) { res.writeHead(400).end('rotation disallowed'); return; }
      devices.set(sender, { ...msg.register, generation: 1, active: true });
    } else {
      const kind = msg.send_initial ? 'send_initial' : 'send';
      const item = msg[kind];
      const receiver = devices.get(item.recipient), author = devices.get(sender);
      if (!receiver?.active || !author?.active || receiver.generation !== item.recipient_generation) {
        res.writeHead(400).end('device changed'); return;
      }
      if (kind === 'send_initial') {
        const index = receiver.prekeys.findIndex(key => key.id === item.prekey_id);
        if (index < 0) { res.writeHead(400).end('prekey spent'); return; }
        receiver.prekeys.splice(index, 1);
      }
      sequence++;
      const entry = { sequence, message_id: item.message_id, sender, sender_generation: author.generation,
        recipient: item.recipient, recipient_generation: receiver.generation,
        kind: kind === 'send_initial' ? { initial: { prekey_id: item.prekey_id } } : 'followup',
        ciphertext: item.ciphertext };
      inbox.set(item.recipient, [...(inbox.get(item.recipient) || []), entry]);
      sent.set(sender + ':' + item.message_id, sequence);
    }
    res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify({ transactionHash: 'mock-uni7-tx' }));
    return;
  }
  if (path === '/assets/socials-testnet-client.js') {
    res.writeHead(200, { 'content-type': 'text/javascript' }).end(stub); return;
  }
  const file = files[path];
  if (!file) { res.writeHead(404).end(); return; }
  try {
    const type = path.endsWith('.wasm') ? 'application/wasm' : path.endsWith('.css') ? 'text/css' :
      path.endsWith('.html') ? 'text/html' : 'text/javascript';
    res.writeHead(200, { 'content-type': type }).end(await readFile(file));
  } catch (error) { res.writeHead(500).end(error.message); }
});
